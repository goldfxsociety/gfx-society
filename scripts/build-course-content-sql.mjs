#!/usr/bin/env node
// Builds an idempotent SQL file from course content JSON (format: see FORMAT.md in the content folder).
// Usage: node scripts/build-course-content-sql.mjs <content-dir> > supabase/migrations/<timestamp>_course_content.sql
// Output is reviewed in a PR. Applying it to prod needs Ben's OK.
import fs from "node:fs";
import path from "node:path";
import os from "node:os";
import { spawnSync } from "node:child_process";

// --dry-run: parse + validate only; prints a summary to stderr and writes no SQL.
const args = process.argv.slice(2);
const dryRun = args.includes("--dry-run");
const dir = args.find((a) => !a.startsWith("--"));
if (!dir) { console.error("usage: build-course-content-sql.mjs [--dry-run] <content-dir>"); process.exit(2); }
const SLUG = /^[a-z0-9-]+$/;
const errors = [];
const fail = (where, msg) => errors.push(`${where}: ${msg}`);
const read = (f) => { try { return JSON.parse(fs.readFileSync(f, "utf8")); } catch (e) { fail(f, `bad JSON (${e.message})`); return null; } };
const q = (s) => { const t = String(s ?? ""); if (t.includes("$gfx$")) fail("text", "must not contain $gfx$"); return `$gfx$${t}$gfx$`; };
const j = (v) => `${q(JSON.stringify(v))}::jsonb`;

function checkQuestions(where, qs, exact) {
  if (!Array.isArray(qs)) return fail(where, "questions must be an array");
  if (exact && qs.length !== exact) fail(where, `needs exactly ${exact} questions, has ${qs.length}`);
  qs.forEach((x, i) => {
    const w = `${where} q${i + 1}`;
    if (!x?.prompt?.trim()) fail(w, "prompt missing");
    if (!Array.isArray(x?.options) || x.options.length < 2 || x.options.length > 5) fail(w, "options: 2-5 strings");
    if (!Number.isInteger(x?.correct) || x.correct < 0 || x.correct >= (x.options?.length ?? 0)) fail(w, "correct must be a 0-based index into options");
    if (!x?.explanation?.trim()) fail(w, "explanation missing");
  });
}
// Optional 'disclaimer' (placement.json, capstone.json): trimmed string, max 500 chars, no income/profit/win-rate
// or other banned wording. Optional extra check: set GFX_COMPLIANCE_CHECK to compliance_check.py to run it too.
const BANNED = /\b(income|profit|profits|kita|kumita|win[- ]?rate|winrate|guarantee[ds]?|garantisado|sure ?win|signals?|vip|pde|passive|returns?|roi)\b|\d+\s*%\s*(win|accuracy|return)/i;
function checkDisclaimer(where, v) {
  if (v === undefined || v === null) return null;
  if (typeof v !== "string") { fail(where, "disclaimer must be a string"); return null; }
  const t = v.trim();
  if (!t) return null;
  if (t.length > 500) fail(where, "disclaimer max 500 chars");
  if (BANNED.test(t)) fail(where, `disclaimer has banned wording (${t.match(BANNED)[0]})`);
  if (process.env.GFX_COMPLIANCE_CHECK) {
    const tmp = path.join(os.tmpdir(), `gfx-disclaimer-${process.pid}.txt`);
    fs.writeFileSync(tmp, t);
    const r = spawnSync("python3", [process.env.GFX_COMPLIANCE_CHECK, tmp, "--platform", "site"], { encoding: "utf8" });
    fs.rmSync(tmp, { force: true });
    if (r.status !== 0) fail(where, "disclaimer fails compliance_check.py");
  }
  return t;
}
const summary = [];
const toDb = (qs) => qs.map((x) => ({ q: x.prompt, options: x.options, answer_index: x.correct, explain: x.explanation }));

const out = ["-- Generated by scripts/build-course-content-sql.mjs. Do not edit by hand; edit the content files and regenerate.", "-- Idempotent: safe to run twice. Courses must already exist (seed).", "begin;"];
for (const course of fs.readdirSync(dir).filter((d) => fs.statSync(path.join(dir, d)).isDirectory()).sort()) {
  if (!SLUG.test(course)) { fail(course, "course folder must be a slug"); continue; }
  const cdir = path.join(dir, course);
  const modsFile = path.join(cdir, "modules.json");
  const mods = fs.existsSync(modsFile) ? read(modsFile) : [];
  const seenSort = new Set();
  for (const m of mods ?? []) {
    const w = `${course}/modules.json ${m?.slug}`;
    if (!SLUG.test(m?.slug ?? "")) fail(w, "slug");
    if (!m?.title) fail(w, "title");
    if (!Number.isInteger(m?.order) || seenSort.has(m.order)) fail(w, "order must be a unique integer"); else seenSort.add(m.order);
    out.push(`insert into public.training_modules (course_id, sort, slug, title, learning_goal, practice_task)
select c.id, ${m.order}, ${q(m.slug)}, ${q(m.title)}, ${q(m.learning_goal)}, ${q(m.practice_task)} from public.training_courses c where c.slug = ${q(course)}
on conflict (course_id, slug) do update set sort = excluded.sort, title = excluded.title, learning_goal = excluded.learning_goal, practice_task = excluded.practice_task;`);
  }
  const ldir = path.join(cdir, "lessons");
  for (const mod of fs.existsSync(ldir) ? fs.readdirSync(ldir).sort() : []) {
    const lessonSorts = new Set();
    for (const f of fs.readdirSync(path.join(ldir, mod)).filter((f) => f.endsWith(".json")).sort()) {
      const w = `${course}/lessons/${mod}/${f}`;
      const L = read(path.join(ldir, mod, f)); if (!L) continue;
      const slug = f.replace(/\.json$/, "");
      if (!SLUG.test(slug)) fail(w, "file name must be the lesson slug");
      if (!L.title) fail(w, "title");
      if (!Number.isInteger(L.order) || lessonSorts.has(L.order)) fail(w, "order must be a unique integer in the module"); else lessonSorts.add(L.order);
      if (!["draft", "published"].includes(L.status)) fail(w, "status must be draft or published");
      if (L.quiz) checkQuestions(w + " quiz", L.quiz);
      out.push(`insert into public.training_lessons (module_id, sort, slug, title, tldr, body_md, takeaway, practice_task, status)
select m.id, ${L.order}, ${q(slug)}, ${q(L.title)}, ${q(L.tldr)}, ${q(L.body)}, ${q(L.takeaway)}, ${q(L.practice_task)}, ${q(L.status)}
from public.training_modules m join public.training_courses c on c.id = m.course_id where c.slug = ${q(course)} and m.slug = ${q(mod)}
on conflict (module_id, slug) do update set sort = excluded.sort, title = excluded.title, tldr = excluded.tldr, body_md = excluded.body_md, takeaway = excluded.takeaway, practice_task = excluded.practice_task, status = excluded.status;`);
      if (L.quiz?.length) out.push(`insert into private.training_quizzes (lesson_id, questions)
select l.id, ${j(toDb(L.quiz))} from public.training_lessons l join public.training_modules m on m.id = l.module_id join public.training_courses c on c.id = m.course_id
where c.slug = ${q(course)} and m.slug = ${q(mod)} and l.slug = ${q(slug)}
on conflict (lesson_id) do update set questions = excluded.questions;`);
    }
  }
  const pf = path.join(cdir, "placement.json");
  if (fs.existsSync(pf)) { const P = read(pf); if (P) { checkQuestions(`${course}/placement.json`, P.questions, 10);
    const D = checkDisclaimer(`${course}/placement.json`, P.disclaimer);
    summary.push(`${course}/placement.json: ${P.questions?.length ?? 0} questions, disclaimer: ${D === null ? "(none -> default risk line)" : JSON.stringify(D)}`);
    out.push(`insert into private.placement_quizzes (course_id, questions, disclaimer) select c.id, ${j(toDb(P.questions ?? []))}, ${D === null ? "null" : q(D)} from public.training_courses c where c.slug = ${q(course)}
on conflict (course_id) do update set questions = excluded.questions, disclaimer = excluded.disclaimer;`); } }
  const kf = path.join(cdir, "capstone.json");
  if (fs.existsSync(kf)) { const K = read(kf); if (K) {
    if (!K.title) fail(`${course}/capstone.json`, "title");
    if (!Array.isArray(K.rubric) || !K.rubric.length || K.rubric.some((r) => typeof r !== "string" || !r.trim())) fail(`${course}/capstone.json`, "rubric must be a non-empty array of strings");
    const D = checkDisclaimer(`${course}/capstone.json`, K.disclaimer);
    summary.push(`${course}/capstone.json: ${K.rubric?.length ?? 0} rubric items, disclaimer: ${D === null ? "(none -> default risk line)" : JSON.stringify(D)}`);
    out.push(`insert into public.training_capstones (course_id, title, rubric, disclaimer) select c.id, ${q(K.title)}, ${j(K.rubric ?? [])}, ${D === null ? "null" : q(D)} from public.training_courses c where c.slug = ${q(course)}
on conflict (course_id) do update set title = excluded.title, rubric = excluded.rubric, disclaimer = excluded.disclaimer;`); } }
}
out.push("commit;");
if (errors.length) { console.error(errors.map((e) => "ERROR " + e).join("\n")); process.exit(1); }
if (dryRun) { console.error(["DRY RUN OK (no SQL written)", ...summary, `${out.length - 4} upsert statements would be generated`].join("\n")); process.exit(0); }
process.stdout.write(out.join("\n\n") + "\n");
